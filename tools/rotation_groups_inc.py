"""Таблица составных предметов для повёрнутой карты: src/Engine/HdTurnGroupsTable.inc.

Источник - census/rotation/composite.tsv (tools/rotation_step2.py, обе игры). Каждая группа - записи
объектов MCD «набор:запись» на местах x, y, z (z вверх) относительно угла рамки группы. Движок
(HdTurnGroups) находит такие группы на карте боя и при повороте рисует их целиком: клетке вида отдаётся
кусок, который стоит на её месте в целом (при нечётном повороте - зеркало целого).

Берутся только группы «перестановка_кусков» - целое одинаково со всех сторон (растение или зеркало целого
совпадает с ним на 0.92+). Группы «вид_целиком» (машины, корабли) зеркало рамки отрывает от соседних кусков:
кабина драккара на пробе собралась, а нос и гондола съехали с корпуса. Им нужен нарисованный вид.

Группы с одинаковым составом (один набор в двух играх) пишутся один раз.

    py -3 tools/rotation_groups_inc.py            # пишет src/Engine/HdTurnGroupsTable.inc
    py -3 tools/rotation_groups_inc.py --check    # только сверяет файл с таблицей, код 1 - расходится
"""
import argparse
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "census", "rotation", "composite.tsv")
OUT = os.path.join(ROOT, "src", "Engine", "HdTurnGroupsTable.inc")


def read_groups(path):
    groups = []
    seen = set()
    with open(path, encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f, delimiter="\t"):
            # только целые, одинаковые со всех сторон (растения и сам-зеркальные, подтверждены Vitali 20.10):
            # несимметричное целое зеркалом рамки отрывается от соседей, ему нужен нарисованный вид
            if row["поворот"] != "перестановка_кусков":
                continue
            pieces = []
            for item in row["состав_набор:запись@x,y,z"].split():
                name, rest = item.rsplit(":", 1)
                rec, at = rest.split("@")
                x, y, z = (int(v) for v in at.split(","))
                pieces.append((name.upper(), int(rec), x, y, z))
            pieces.sort(key=lambda p: (p[4], p[3], p[2], p[0], p[1]))
            key = tuple(pieces)
            if key in seen:
                continue
            seen.add(key)
            ext = [max(p[2 + i] for p in pieces) + 1 for i in range(3)]
            groups.append((row["группа"], row["игра"], pieces, ext))
    return groups


def render(groups):
    sets = sorted({p[0] for _, _, pieces, _ in groups for p in pieces})
    index = {s: i for i, s in enumerate(sets)}
    out = ["// The composite objects of the turned map (Engine/HdTurnGroups.h): generated by tools/rotation_groups_inc.py",
           "// from census/rotation/composite.tsv - do not edit. %d groups, %d pieces, %d terrain sets."
           % (len(groups), sum(len(g[2]) for g in groups), len(sets)),
           "",
           "static const char *const TURN_GROUP_SETS[] =",
           "{"]
    out += ['\t"%s",' % s for s in sets]
    out += ["};", "", "static const HdTurnGroupPiece TURN_GROUP_PIECES[] =", "{"]
    first = []
    n = 0
    for gid, game, pieces, _ in groups:
        first.append(n)
        out.append("\t// %s %s" % (gid, game))
        out += ["\t{ %d, %d, %d, %d, %d }," % (index[s], rec, x, y, z) for s, rec, x, y, z in pieces]
        n += len(pieces)
    out += ["};", "", "static const HdTurnGroupDef TURN_GROUP_DEFS[] =", "{"]
    for (gid, game, pieces, ext), f in zip(groups, first):
        out.append("\t{ %d, %d, %d, %d, %d }, // %s" % (f, len(pieces), ext[0], ext[1], ext[2], gid))
    out += ["};", ""]
    return "\n".join(out)


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(read_groups(SRC))
    if a.check:
        old = open(OUT, encoding="utf-8", newline="").read() if os.path.exists(OUT) else ""
        same = old == text
        print("таблица %s" % ("совпадает" if same else "РАСХОДИТСЯ"))
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("записано %s: %s" % (os.path.relpath(OUT, ROOT), text.split("\n")[1][3:]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
